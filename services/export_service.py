"""
Export service for CallSense call analytics.
Provides:
1. True Excel (.xlsx) export using openpyxl with professional styling, auto-column widths, and zebra striping.
2. Secure individual Call PDF export using ReportLab with strict ownership verification, 404 handling,
   and role-based privacy redaction (excluding transcripts & phone numbers for shared recipients).
"""
