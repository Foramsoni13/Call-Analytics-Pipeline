class NumberedCanvas(canvas.Canvas):
    """Canvas that computes total pages for 'Page X of Y' footer."""
    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_number(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)

    def draw_page_number(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748B"))
        # Footer line
        self.setStrokeColor(colors.HexColor("#E2E8F0"))
        self.setLineWidth(0.5)
        self.line(36, 32, letter[0] - 36, 32)
        # Footer text
        footer_text = f"CallSense Analytics Report  |  Page {self._pageNumber} of {page_count}"
        self.drawString(36, 20, footer_text)
        conf_text = "Confidential & Proprietary"
        self.drawRightString(letter[0] - 36, 20, conf_text)
        self.restoreState()


def generate_calls_excel(calls_list: list, requester_username: str = "User") -> io.BytesIO:
    """
    Generates a real, beautifully formatted Excel (.xlsx) workbook using openpyxl.
    Includes summary headers, auto-adjusted column widths, and zebra row styling.
    """
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Call Analytics"
    ws.views.sheetView[0].showGridLines = True

    # Palette
    HEADER_FILL = PatternFill(start_color="0F172A", end_color="0F172A", fill_type="solid")
    HEADER_FONT = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
    ZEBRA_FILL = PatternFill(start_color="F8FAFC", end_color="F8FAFC", fill_type="solid")
    WHITE_FILL = PatternFill(start_color="FFFFFF", end_color="FFFFFF", fill_type="solid")
    TITLE_FONT = Font(name="Calibri", size=16, bold=True, color="0F172A")
    META_FONT = Font(name="Calibri", size=10, italic=True, color="475569")
    REGULAR_FONT = Font(name="Calibri", size=10, color="1E293B")
    BOLD_FONT = Font(name="Calibri", size=10, bold=True, color="1E293B")

    thin_border = Border(
        left=Side(style="thin", color="E2E8F0"),
        right=Side(style="thin", color="E2E8F0"),
        top=Side(style="thin", color="E2E8F0"),
        bottom=Side(style="thin", color="E2E8F0"),
    )

    # 1. Title Block
    ws.append(["CallSense — Call Analytics & Intelligence Report"])
    ws.cell(row=1, column=1).font = TITLE_FONT
    ws.append([f"Generated by: {requester_username}  |  Date: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}  |  Total Records: {len(calls_list)}"])
    ws.cell(row=2, column=1).font = META_FONT
    ws.append([])  # blank line

    # 2. Table Headers
    headers = [
        "File Name",
        "Uploaded Date",
        "Status",
        "Language",
        "Customer Name",
        "Agent Name",
        "Category",
        "Sentiment",
        "Priority",
        "Resolution",
        "Confidence (%)",
        "Duration (s)",
        "Summary",
        "Key Issues",
        "Action Items",
        "Follow-up Needed",
        "Access Type",
    ]
    ws.append(headers)
    header_row_idx = 4

    for col_idx in range(1, len(headers) + 1):
        cell = ws.cell(row=header_row_idx, column=col_idx)
        cell.fill = HEADER_FILL
        cell.font = HEADER_FONT
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = thin_border
    ws.row_dimensions[header_row_idx].height = 28

    # 3. Populate Rows
    for r_idx, call in enumerate(calls_list, start=header_row_idx + 1):
        created_at = call.get("created_at")
        date_str = created_at.strftime("%Y-%m-%d %H:%M") if hasattr(created_at, "strftime") else (str(created_at) if created_at else "—")
        
        # Format key issues & action items
        issues_list = call.get("key_issues", [])
        issues_str = "; ".join(issues_list) if isinstance(issues_list, list) else str(issues_list or "")
        actions_list = call.get("action_items", [])
        actions_str = "; ".join(actions_list) if isinstance(actions_list, list) else str(actions_list or "")
        
        conf = call.get("confidence_percent")
        conf_val = f"{conf}%" if conf is not None else "—"
        dur = call.get("audio_duration_seconds")
        dur_val = round(dur, 1) if dur is not None else "—"

        access_type = call.get("export_access_type", "My Call")

        row_data = [
            call.get("filename", "—"),
            date_str,
            (call.get("status") or "").replace("_", " ").title(),
            call.get("language", "—"),
            call.get("customer_name") or "—",
            call.get("agent_name") or "—",
            call.get("category", "—"),
            call.get("sentiment", "—"),
            call.get("priority", "—"),
            call.get("resolution_status", "—"),
            conf_val,
            dur_val,
            call.get("summary") or "—",
            issues_str or "—",
            actions_str or "—",
            "Yes" if call.get("follow_up_required") else "No",
            access_type,
        ]
        ws.append(row_data)

        row_fill = ZEBRA_FILL if (r_idx % 2 == 0) else WHITE_FILL
        for c_idx, val in enumerate(row_data, start=1):
            cell = ws.cell(row=r_idx, column=c_idx)
            cell.fill = row_fill
            cell.font = REGULAR_FONT
            cell.border = thin_border
            
            # Alignments
            if c_idx in (2, 3, 4, 8, 9, 10, 11, 12, 16, 17):
                cell.alignment = Alignment(horizontal="center", vertical="top")
            elif c_idx in (13, 14, 15):
                cell.alignment = Alignment(horizontal="left", vertical="top", wrap_text=True)
            else:
                cell.alignment = Alignment(horizontal="left", vertical="top")

        ws.row_dimensions[r_idx].height = 22

    # 4. Auto-fit column widths (with sane bounds)
    for col in ws.columns:
        col_letter = get_column_letter(col[0].column)
        if col[0].row > header_row_idx:
            continue
        max_len = 0
        for cell in col[header_row_idx - 1:]:
            val = str(cell.value or "")
            # Don't let long summary blow column width out
            if len(val) > max_len:
                max_len = len(val)
        col_width = min(max(max_len + 4, 12), 45)
        ws.column_dimensions[col_letter].width = col_width

    # Summary & Action item columns fixed widths for readability
    ws.column_dimensions["M"].width = 45  # Summary
    ws.column_dimensions["N"].width = 30  # Key Issues
    ws.column_dimensions["O"].width = 30  # Action Items

    buffer = io.BytesIO()
    wb.save(buffer)
    buffer.seek(0)
    return buffer


def generate_single_call_pdf(call: dict, requester_id: str, is_admin: bool = False) -> io.BytesIO:
    """
    Generates a secure, highly styled PDF analytics report for a single call record.
    Security & Privacy Rules:
    - 404: Caller must verify `call is not None` before calling, or handle 404.
    - Security/Access Check: Must be Owner, Admin, or Shared Recipient.
    - Privacy Mismatch Resolution:
      * Owner / Admin: Full report INCLUDING complete transcripts (Original, Gujarati, Hindi, English).
      * Shared Recipient: Analytics Summary Report (Category, Motive, Summary, Action Items)
        with raw transcripts and phone numbers strictly redacted for privacy protection.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=36,
        rightMargin=36,
        topMargin=36,
        bottomMargin=46,
    )

    is_owner = (str(call.get("uploaded_by")) == str(requester_id))
    has_full_transcript_access = is_owner or is_admin

    styles = getSampleStyleSheet()

    # Custom typography styles
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0F172A"),
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#64748B"),
    )
    section_h1 = ParagraphStyle(
        "SectionH1",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=12,
        leading=16,
        textColor=colors.HexColor("#0F172A"),
        spaceBefore=10,
        spaceAfter=4,
    )
    body_style = ParagraphStyle(
        "BodyTextCustom",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#1E293B"),
    )
    body_bold = ParagraphStyle(
        "BodyBoldCustom",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#0F172A"),
    )
    label_style = ParagraphStyle(
        "LabelStyle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#475569"),
    )
    value_style = ParagraphStyle(
        "ValueStyle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=12,
        textColor=colors.HexColor("#0F172A"),
    )
    badge_style = ParagraphStyle(
        "BadgeStyle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8,
        leading=10,
        textColor=colors.white,
        alignment=1,
    )
    transcript_text = ParagraphStyle(
        "TranscriptText",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=12,
        textColor=colors.HexColor("#1E293B"),
    )
    privacy_notice_style = ParagraphStyle(
        "PrivacyNotice",
        parent=styles["Normal"],
        fontName="Helvetica-Oblique",
        fontSize=8.5,
        leading=12,
        textColor=colors.HexColor("#94A3B8"),
    )

    story = []

    # 1. Header Banner
    report_type = "Executive Intelligence & Transcript Report" if has_full_transcript_access else "Shared Analytics Summary Report"
    privacy_badge = "CONFIDENTIAL · FULL AUDIT" if has_full_transcript_access else "SHARED VIEW · TRANSCRIPT REDACTED"
    badge_bg = colors.HexColor("#1E40AF") if has_full_transcript_access else colors.HexColor("#475569")

    header_table_data = [
        [
            Paragraph("<b>CallSense</b> · Multi-Lingual Speech Intelligence", title_style),
            Table([[Paragraph(f"<b>{privacy_badge}</b>", badge_style)]],
                  colWidths=[180],
                  style=[
                      ('BACKGROUND', (0, 0), (-1, -1), badge_bg),
                      ('ALIGN', (0, 0), (-1, -1), 'CENTER'),
                      ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
                      ('TOPPADDING', (0, 0), (-1, -1), 3),
                      ('BOTTOMPADDING', (0, 0), (-1, -1), 3),
                  ])
        ],
        [
            Paragraph(f"Report: {report_type}  |  Generated: {datetime.now(timezone.utc).strftime('%B %d, %Y at %H:%M UTC')}", subtitle_style),
            ""
        ]
    ]
    t_header = Table(header_table_data, colWidths=[360, 180])
    t_header.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('SPAN', (0, 1), (1, 1)),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 2),
    ]))
    story.append(t_header)
    story.append(Spacer(1, 4))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#E2E8F0"), spaceBefore=2, spaceAfter=8))

    # 2. File & Call Metadata Box
    created_at = call.get("created_at")
    created_str = created_at.strftime("%d %b %Y, %H:%M UTC") if hasattr(created_at, "strftime") else (str(created_at) if created_at else "—")
    dur = call.get("audio_duration_seconds")
    dur_str = f"{round(dur, 1)}s" if dur is not None else "—"
    conf = call.get("confidence_percent")
    conf_str = f"{conf}%" if conf is not None else "—"

    # Privacy filter for phone numbers
    if has_full_transcript_access:
        phone_nums = call.get("phone_numbers_mentioned", [])
        phone_str = ", ".join(phone_nums) if phone_nums else "None detected"
    else:
        phone_str = "Redacted (Protected Contact Data)"

    meta_grid = [
        [
            Paragraph("FILE NAME", label_style),
            Paragraph("STATUS", label_style),
            Paragraph("LANGUAGE", label_style),
            Paragraph("DURATION", label_style),
            Paragraph("CONFIDENCE", label_style),
        ],
        [
            Paragraph(call.get("filename", "—"), value_style),
            Paragraph((call.get("status") or "completed").replace("_", " ").title(), value_style),
            Paragraph(call.get("language", "—"), value_style),
            Paragraph(dur_str, value_style),
            Paragraph(conf_str, value_style),
        ],
        [
            Paragraph("CUSTOMER NAME", label_style),
            Paragraph("AGENT NAME", label_style),
            Paragraph("CATEGORY", label_style),
            Paragraph("SENTIMENT", label_style),
            Paragraph("PRIORITY", label_style),
        ],
        [
            Paragraph(call.get("customer_name") or "Unspecified", value_style),
            Paragraph(call.get("agent_name") or "Unspecified", value_style),
            Paragraph(call.get("category", "—"), value_style),
            Paragraph(call.get("sentiment", "—"), value_style),
            Paragraph(call.get("priority", "—"), value_style),
        ],
        [
            Paragraph("UPLOADED AT", label_style),
            Paragraph("RESOLUTION STATUS", label_style),
            Paragraph("FOLLOW-UP NEEDED", label_style),
            Paragraph("PHONE NUMBERS", label_style),
            Paragraph("", label_style),
        ],
        [
            Paragraph(created_str, value_style),
            Paragraph(call.get("resolution_status", "—"), value_style),
            Paragraph("Yes (Action Required)" if call.get("follow_up_required") else "No", value_style),
            Paragraph(phone_str, value_style),
            Paragraph("", value_style),
        ]
    ]
    t_meta = Table(meta_grid, colWidths=[130, 100, 100, 100, 110])
    t_meta.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ('TOPPADDING', (0, 0), (-1, -1), 3),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('SPAN', (3, 4), (4, 4)),
        ('SPAN', (3, 5), (4, 5)),
    ]))
    story.append(t_meta)
    story.append(Spacer(1, 8))

    # 3. Call Motive & AI Summary
    story.append(Paragraph("Executive Summary & Call Motive", section_h1))
    motive_text = call.get("motive_english") or call.get("motive") or "Not determined."
    summary_text = call.get("summary_english") or call.get("summary") or "No summary available."
    native_summary = call.get("summary")

    summary_rows = [
        [Paragraph("<b>Call Motive:</b>", body_bold), Paragraph(motive_text, body_style)],
        [Paragraph("<b>Summary (EN):</b>", body_bold), Paragraph(summary_text, body_style)],
    ]
    if native_summary and native_summary != summary_text and call.get("language") != "English":
        summary_rows.append([
            Paragraph(f"<b>Summary ({call.get('language')}):</b>", body_bold),
            Paragraph(native_summary, body_style)
        ])

    t_summary = Table(summary_rows, colWidths=[110, 430])
    t_summary.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#FFFFFF")),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ('LINEBELOW', (0, 0), (-1, -2), 0.5, colors.HexColor("#F1F5F9")),
    ]))
    story.append(t_summary)
    story.append(Spacer(1, 8))

    # 4. Key Issues & Action Items
    story.append(Paragraph("Structured Insights & Commitments", section_h1))
    issues = call.get("key_issues", [])
    actions = call.get("action_items", [])

    issues_p = "<br/>".join([f"&bull; {item}" for item in issues]) if issues else "None identified."
    actions_p = "<br/>".join([f"&bull; {item}" for item in actions]) if actions else "No explicit action items."

    insights_data = [
        [Paragraph("<b>Customer Key Issues</b>", body_bold), Paragraph("<b>Agent Commitments & Action Items</b>", body_bold)],
        [Paragraph(issues_p, body_style), Paragraph(actions_p, body_style)]
    ]
    t_insights = Table(insights_data, colWidths=[270, 270])
    t_insights.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor("#F1F5F9")),
        ('BACKGROUND', (0, 1), (-1, 1), colors.HexColor("#FFFFFF")),
        ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
        ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('TOPPADDING', (0, 0), (-1, -1), 4),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
    ]))
    story.append(t_insights)
    story.append(Spacer(1, 8))

    # 5. Transcripts Section (Protected / Role-Based Access)
    story.append(Paragraph("Conversation Transcripts & Translations", section_h1))

    if has_full_transcript_access:
        # Full transcripts available to Owner & Admin
        transcript_boxes = []

        # Original ASR
        orig_t = call.get("transcript") or "No transcript recorded."
        transcript_boxes.append([
            Paragraph(f"<b>Original Transcript ({call.get('language') or 'Audio'})</b>", label_style),
            Paragraph(orig_t, transcript_text)
        ])

        # English Translation
        en_t = call.get("transcript_english")
        if en_t and call.get("language") != "English":
            transcript_boxes.append([
                Paragraph("<b>English Translation</b>", label_style),
                Paragraph(en_t, transcript_text)
            ])

        # Hindi Translation / Cleaned Hindi
        hi_t = call.get("transcript_hindi")
        if hi_t:
            hi_label = "Cleaned Hindi (Devanagari)" if call.get("language") == "Hindi" else "Hindi Translation"
            transcript_boxes.append([
                Paragraph(f"<b>{hi_label}</b>", label_style),
                Paragraph(hi_t, transcript_text)
            ])

        # Gujarati Translation / Cleaned Gujarati
        gu_t = call.get("transcript_gujarati")
        if gu_t:
            gu_label = "Cleaned Gujarati" if call.get("language") == "Gujarati" else "Gujarati Translation"
            transcript_boxes.append([
                Paragraph(f"<b>{gu_label}</b>", label_style),
                Paragraph(gu_t, transcript_text)
            ])

        t_transcripts = Table(transcript_boxes, colWidths=[120, 420])
        t_transcripts.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (0, -1), colors.HexColor("#F8FAFC")),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ('INNERGRID', (0, 0), (-1, -1), 0.5, colors.HexColor("#E2E8F0")),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('TOPPADDING', (0, 0), (-1, -1), 4),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 4),
        ]))
        story.append(t_transcripts)
    else:
        # Privacy Mismatch Protected Notice for Shared Recipients
        redacted_box = [
            [
                Paragraph("<b>TRANSCRIPTS & AUDIO RECORDINGS PROTECTED BY PRIVACY POLICY</b><br/>"
                          "In compliance with CallSense privacy safeguards, raw speech-to-text transcripts, "
                          "voice recordings, and phone numbers are strictly restricted to the call owner and administrators. "
                          "As an authorized shared recipient, you have access to complete analytic summaries, motives, "
                          "categorization, sentiment, and action items above.", privacy_notice_style)
            ]
        ]
        t_redacted = Table(redacted_box, colWidths=[540])
        t_redacted.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), colors.HexColor("#F8FAFC")),
            ('BOX', (0, 0), (-1, -1), 0.5, colors.HexColor("#CBD5E1")),
            ('TOPPADDING', (0, 0), (-1, -1), 8),
            ('BOTTOMPADDING', (0, 0), (-1, -1), 8),
            ('LEFTPADDING', (0, 0), (-1, -1), 10),
            ('RIGHTPADDING', (0, 0), (-1, -1), 10),
        ]))
        story.append(t_redacted)

    # Build document
    doc.build(story, canvasmaker=NumberedCanvas)
    buffer.seek(0)
    return buffer
